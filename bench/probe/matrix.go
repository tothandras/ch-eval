package probe

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

// Matrix is docs/feature-matrix.yaml.
type Matrix struct {
	Preamble string    `yaml:"preamble"`
	Sections []Section `yaml:"sections"`
}

// Section is one numbered section of the matrix (or a prose-only section).
type Section struct {
	Title         string              `yaml:"title"`
	Number        int                 `yaml:"number,omitempty"`
	Intro         string              `yaml:"intro,omitempty"`
	Columns       []string            `yaml:"columns,omitempty"`
	ColumnTargets map[string][]string `yaml:"column_targets,omitempty"`
	Rows          []Row               `yaml:"rows,omitempty"`
	Outro         string              `yaml:"outro,omitempty"`
}

// Row is one capability with its cited hypothesis per column.
type Row struct {
	ID                string            `yaml:"id"`
	OpenMeterRelevant bool              `yaml:"openmeter_relevant,omitempty"`
	Evidence          string            `yaml:"evidence,omitempty"`
	Probes            []string          `yaml:"probes,omitempty"`
	Cells             map[string]string `yaml:"cells"`
}

// LoadMatrix reads the YAML source of truth.
func LoadMatrix(path string) (*Matrix, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var m Matrix
	if err := yaml.Unmarshal(b, &m); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &m, nil
}

// TargetResult is the latest probe outcome of one probe on one platform.
type TargetResult struct {
	Platform string
	Tier     string
	Version  string
	RunID    string
	Result   Result
}

const hypothesisMark = "*(h)*"

// Render produces docs/feature-matrix.md. results maps probe path -> platform ->
// latest result; a cell covering platforms whose probes all ran shows the probed
// outcome with the exact version instead of the hypothesis marker.
func (m *Matrix) Render(results map[string]map[string]TargetResult, status string) string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `bench feature-matrix` from docs/feature-matrix.yaml and results/probes/. Do not edit. -->\n\n")
	pre := m.Preamble
	if i := strings.Index(pre, "> **Status:"); i >= 0 {
		// The status block is regenerated from the probe coverage.
		j := strings.Index(pre[i:], "\n\n")
		if j > 0 {
			pre = pre[:i] + status + pre[i+j:]
		}
	}
	b.WriteString(strings.TrimRight(pre, "\n") + "\n")
	for _, s := range m.Sections {
		if s.Number > 0 {
			fmt.Fprintf(&b, "\n## %d. %s\n", s.Number, s.Title)
		} else {
			fmt.Fprintf(&b, "\n## %s\n", s.Title)
		}
		if s.Intro != "" {
			b.WriteString("\n" + s.Intro + "\n")
		}
		if len(s.Columns) > 0 {
			b.WriteString("\n| " + strings.Join(s.Columns, " | ") + " |\n|")
			for range s.Columns {
				b.WriteString(" --- |")
			}
			b.WriteString("\n")
			for _, r := range s.Rows {
				cells := make([]string, 0, len(s.Columns))
				id := r.ID
				if r.OpenMeterRelevant {
					id = "**" + id + "**"
				}
				cells = append(cells, id)
				for _, c := range s.Columns[1:] {
					if isEvidenceColumn(c) {
						cells = append(cells, r.Evidence)
						continue
					}
					cells = append(cells, renderCell(r, r.Cells[c], s.ColumnTargets[c], results))
				}
				b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
			}
		}
		if s.Outro != "" {
			b.WriteString("\n" + s.Outro + "\n")
		}
	}
	return b.String()
}

func isEvidenceColumn(c string) bool {
	switch c {
	case "Planned probe", "Probe / evidence", "Planned probe / experiment", "Planned experiment":
		return true
	}
	return false
}

// renderCell appends probe outcomes for the platforms the column covers. The
// hypothesis marker is dropped only when every covered platform ran every probe
// of the row.
func renderCell(r Row, text string, platforms []string, results map[string]map[string]TargetResult) string {
	if len(platforms) == 0 || len(r.Probes) == 0 {
		return text
	}
	var notes []string
	complete := true
	for _, p := range platforms {
		for _, path := range r.Probes {
			tr, ok := results[path][p]
			if !ok {
				complete = false
				continue
			}
			mark := "✔ confirmed"
			if !tr.Result.Pass {
				mark = "✘ contradicted (observed " + tr.Result.Observed.String() + ")"
			}
			notes = append(notes, fmt.Sprintf("%s %s on `%s` (%s)", p, mark, tr.Version, shortProbe(path)))
		}
	}
	if len(notes) == 0 {
		return text
	}
	sort.Strings(notes)
	if complete {
		text = strings.ReplaceAll(text, " "+hypothesisMark, "")
		text = strings.ReplaceAll(text, hypothesisMark, "")
	}
	return text + "<br>**Probed:** " + strings.Join(notes, "; ")
}

func shortProbe(p string) string { return strings.TrimSuffix(strings.TrimPrefix(p, "probes/"), ".sql") }
